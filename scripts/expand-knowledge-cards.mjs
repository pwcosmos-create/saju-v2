fs.copyFileSync(cardsPath, backupPath);
console.log('Backup created:', backupPath);

const pack = JSON.parse(fs.readFileSync(cardsPath, 'utf8'));
const cards = pack.cards || [];
const existingTitles = new Set(cards.map((c) => (c.title || '').trim()));
let nextId = Math.max(0, ...cards.map((c) => Number(c.id) || 0)) + 1;
let addedCount = 0;

for (const card of EXPAND_CARDS) {
  if (existingTitles.has(card.title.trim())) {
    console.log(`[SKIP] Already exists: ${card.title}`);
    continue;
  }
  cards.push({
    id: nextId++,
    title: card.title.trim(),
    body: card.body.trim(),
    summary: card.summary.trim(),
    tags: card.tags,
    status: 'confirmed',
    council_pass: true,
    council_status: 'pass',
  });
  existingTitles.add(card.title.trim());
  addedCount++;
  console.log(`[ADDED] ${card.title}`);
}

pack.cards = cards;
pack.card_count = cards.length;
pack.updated_at = new Date().toISOString().replace('T', ' ').slice(0, 16);

fs.writeFileSync(cardsPath, `${JSON.stringify(pack, null, 2)}\n`, 'utf8');
console.log(`\n완료: 신규 카드 ${addedCount}장 추가 됨 / 총 ${cards.length}장 보유.`);
